import pptxgen from "pptxgenjs";
import { PPT_COLOR_PALETTE } from "../../../lib/constant.js";

const colors = PPT_COLOR_PALETTE;

function addCoverPage(ppt, data) {
  const slide = ppt.addSlide();

  slide.background = {
    color: colors.primary,
  };

  // shape
  slide.addShape(ppt.ShapeType.rect, {
    x: 0,
    y: 0,
    w: 13.33,
    h: 0.18,
    fill: {
      color: colors.filler_1,
    },
    line: {
      color: colors.filler_1,
    },
  });

  // title
  slide.addText(data.title, {
    x: 0.7,
    y: 1.7,
    w: 12,
    h: 0.8,
    align: "center",
    color: colors.white,
    bold: true,
    fontSize: 28,
  });

  // subtitle
  slide.addText(data.subtitle, {
    x: 1,
    y: 2.8,
    w: 11.5,
    h: 0.4,
    align: "center",
    color: colors.tetriary,
    fontSize: 15,
  });

  // generated by
  slide.addText("Generated by Choreograph AI", {
    x: 9,
    y: 6.9,
    w: 13.33,
    h: 0.2,
    align: "right",
    color: colors.muted,
    fontSize: 10,
  });

  return ppt;
}

function addContentSlide(ppt, title, points, slidesLength, pageNumber) {
  const slide = ppt.addSlide();

  slide.background = {
    color: colors.white,
  };

  // title
  slide.addText(title, {
    x: 0.6,
    y: 0.35,
    w: 10,
    h: 0.4,
    fontSize: 24,
    color: colors.primary,
    bold: true,
  });

  // shape
  slide.addShape(ppt.ShapeType.line, {
    x: 0.6,
    y: 0.85,
    w: 12,
    h: 0,
    line: {
      color: colors.border,
      width: 1.2,
    },
  });

  // points
  points.forEach((point, index) => {
    const y = 1.2 + index * 0.75;

    slide.addShape(ppt.ShapeType.roundRect, {
      x: 0.7,
      y,
      w: 12,
      h: 0.58,
      fill: {
        color: index % 2 ? colors.filler_2 : colors.filler_3,
      },
      line: {
        color: colors.border,
      },
      radius: 0.08,
    });

    slide.addShape(ppt.ShapeType.ellipse, {
      x: 0.92,
      y: y + 0.18,
      w: 0.12,
      h: 0.12,
      fill: {
        color: colors.primary,
      },
      line: {
        color: colors.primary,
      },
    });

    slide.addText(point, {
      x: 1.2,
      y: y + 0.08,
      w: 11,
      h: 0.35,
      fontSize: 15,
      color: colors.text,
      fit: "shrink",
    });
  });

  // page number
  slide.addText(`${pageNumber}/${slidesLength}`, {
    x: 12.1,
    y: 6.9,
    w: 0.8,
    h: 0.2,
    align: "right",
    fontSize: 10,
    color: colors.muted,
  });

  // watermark
  slide.addText("Generated by Choreograph AI", {
    x: 0.6,
    y: 6.9,
    w: 2,
    h: 0.2,
    fontSize: 10,
    color: colors.muted,
  });

  return ppt;
}

function addConclusion(ppt, conclusion) {
  const slide = ppt.addSlide();

  slide.background = {
    color: colors.white,
  };

  // title
  slide.addText("Conclusion", {
    x: 0.6,
    y: 0.35,
    w: 10,
    h: 0.4,
    fontSize: 24,
    color: colors.primary,
    bold: true,
  });

  // shape
  slide.addShape(ppt.ShapeType.line, {
    x: 0.5,
    y: 0.85,
    w: 12,
    h: 0,
    line: {
      color: colors.border,
      width: 1.2,
    },
  });

  // content
  slide.addText(conclusion, {
    x: 0.06,
    y: 1.2,
    w: 11,
    h: 0.35,
    fontSize: 15,
    color: colors.text,
    fit: "shrink",
  });

  // watermark
  slide.addText("Generated by Choreograph AI", {
    x: 0.6,
    y: 6.9,
    w: 2,
    h: 0.2,
    fontSize: 10,
    color: colors.muted,
  });

  return ppt;
}

function addThankYouPage(ppt) {
  const slide = ppt.addSlide();

  slide.background = {
    color: colors.secondary,
  };

  // title
  slide.addText("Thank You", {
    x: 0,
    y: 2.2,
    w: 13.33,
    h: 0.8,
    fontSize: 34,
    color: colors.white,
    bold: true,
    align: "center",
  });

  // watermark
  slide.addText("Generated by Choreograph AI", {
    x: 0.6,
    y: 6.9,
    w: 2,
    h: 0.2,
    fontSize: 10,
    color: colors.muted,
  });

  return ppt;
}

export default function generatePPT(data) {
  const ppt = new pptxgen();

  ppt.author = "Choreograph AI";
  ppt.company = "Choreograph AI";
  ppt.layout = "LAYOUT_WIDE";
  ppt.title = data.title;
  ppt.subject = data.title;
  ppt.theme = {
    headFontFace: "Aptos",
    bodyFontFace: "Aptos",
    lang: "en-US",
  };

  addCoverPage(ppt, data);

  data?.slides?.forEach((slide, idx) => {
    addContentSlide(
      ppt,
      slide.title,
      slide.points,
      data.slides.length,
      idx + 1,
    );
  });

  addConclusion(ppt, data.conclusion);
  addThankYouPage(ppt);

  return ppt;
}
